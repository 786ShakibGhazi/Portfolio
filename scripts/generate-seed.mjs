// Generates supabase/seed.sql from src/content/fallback.json (the resume-derived content).
// Usage: npm run seed:generate
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const data = JSON.parse(readFileSync(new URL('src/content/fallback.json', root), 'utf8'));

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (o) => `${q(JSON.stringify(o ?? []))}::jsonb`;
const bool = (b) => (b ? 'true' : 'false');
const uuid = (seed) => {
  const h = createHash('md5').update(String(seed)).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};
const values = (rows) => rows.join(',\n    ');

const p = data.profile;
const out = [];
out.push(`-- Generated by scripts/generate-seed.mjs from src/content/fallback.json. Do not edit by hand.
-- Seeds the draft tables and publishes an initial snapshot. Skipped when content already exists.
do $seed$
begin
  if exists (select 1 from public.profile) then
    raise notice 'Seed skipped: portfolio content already exists.';
    return;
  end if;

  perform set_config('app.skip_log', 'on', true);

  insert into public.profile
    (id, full_name, title, headline, intro, bio, roles, stats, focus_areas, email, phone, location, resume_path, avatar_path)
  values
    (1, ${q(p.full_name)}, ${q(p.title)}, ${q(p.headline)}, ${q(p.intro)}, ${q(p.bio)}, ${arr(p.roles)},
     ${json(p.stats)}, ${json(p.focus_areas)}, ${q(p.email)}, ${q(p.phone)}, ${q(p.location)}, ${q(p.resume_path)}, ${q(p.avatar_path)});`);

if (data.social_links?.length) {
  out.push(`
  insert into public.social_links (id, platform, label, url, sort_order) values
    ${values(data.social_links.map((s, i) => `('${uuid(s.id ?? `social-${i}`)}', ${q(s.platform)}, ${q(s.label)}, ${q(s.url)}, ${i + 1})`))};`);
}

out.push(`
  insert into public.skill_categories (id, name, icon, sort_order) values
    ${values(data.skill_categories.map((c, i) => `('${uuid(c.id)}', ${q(c.name)}, ${q(c.icon)}, ${i + 1})`))};`);

const skillRows = data.skill_categories.flatMap((c) =>
  c.skills.map((s, i) => {
    const name = typeof s === 'string' ? s : s.name;
    return `('${uuid(`${c.id}:${name}`)}', '${uuid(c.id)}', ${q(name)}, ${i + 1})`;
  }),
);
out.push(`
  insert into public.skills (id, category_id, name, sort_order) values
    ${values(skillRows)};`);

out.push(`
  insert into public.experiences (id, company, role, location, start_date, end_date, is_current, summary, highlights, tech, sort_order) values
    ${values(
      data.experiences.map(
        (e, i) =>
          `('${uuid(e.id)}', ${q(e.company)}, ${q(e.role)}, ${q(e.location)}, ${q(e.start_date)}, ${q(e.end_date)}, ${bool(e.is_current)}, ${q(e.summary)}, ${arr(e.highlights)}, ${arr(e.tech)}, ${i + 1})`,
      ),
    )};`);

out.push(`
  insert into public.projects (id, title, description, period, tech, image_path, live_url, repo_url, is_featured, sort_order) values
    ${values(
      data.projects.map(
        (r, i) =>
          `('${uuid(r.id)}', ${q(r.title)}, ${q(r.description)}, ${q(r.period)}, ${arr(r.tech)}, ${q(r.image_path)}, ${q(r.live_url)}, ${q(r.repo_url)}, ${bool(r.is_featured)}, ${i + 1})`,
      ),
    )};`);

out.push(`
  insert into public.education (id, institution, qualification, period, grade_label, grade_value, sort_order) values
    ${values(
      data.education.map(
        (r, i) =>
          `('${uuid(r.id)}', ${q(r.institution)}, ${q(r.qualification)}, ${q(r.period)}, ${q(r.grade_label)}, ${q(r.grade_value)}, ${i + 1})`,
      ),
    )};`);

if (data.certifications?.length) {
  out.push(`
  insert into public.certifications (id, title, issuer, issued_on, credential_url, sort_order) values
    ${values(
      data.certifications.map(
        (r, i) => `('${uuid(r.id)}', ${q(r.title)}, ${q(r.issuer)}, ${q(r.issued_on)}, ${q(r.credential_url)}, ${i + 1})`,
      ),
    )};`);
}

out.push(`
  insert into public.achievements (id, title, description, metric, platform, url, sort_order) values
    ${values(
      data.achievements.map(
        (r, i) => `('${uuid(r.id)}', ${q(r.title)}, ${q(r.description)}, ${q(r.metric)}, ${q(r.platform)}, ${q(r.url)}, ${i + 1})`,
      ),
    )};

  insert into public.published_content (id, content, published_at)
  values (1, public._build_portfolio(), now())
  on conflict (id) do update set content = excluded.content, published_at = excluded.published_at;

  update public.site_state
     set draft_updated_at = (select published_at from public.published_content where id = 1)
   where id = 1;
end
$seed$;
`);

writeFileSync(new URL('supabase/seed.sql', root), out.join('\n'), 'utf8');
console.log('Wrote supabase/seed.sql');
